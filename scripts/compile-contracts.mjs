/**
 * compile-contracts.mjs - the ONLY compiler in the deploy path.
 *
 * Runs solc-js directly and emits, for each deployable contract, a TypeScript artifact holding
 * its ABI and creation bytecode (server/utils/<name>-artifact.ts). The deploy script ships that
 * artifact, so the bytecode that lands on chain is the bytecode this script produced. It also
 * writes the exact standard-json input for source verification.
 *
 * Foundry is for TESTS ONLY. These settings must mirror foundry.toml and server/config.ts.
 *
 * Unlike nftlaunchpad2 NOTHING is suppressed: this deploys to Ethereum L1, where the 24,576-byte
 * limit (solc warning 5574) is real. Every warning fails the build.
 *
 *   node scripts/compile-contracts.mjs
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, statSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const solc = require("solc");

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CONTRACTS = join(ROOT, "contracts");
const OUT = join(ROOT, "server", "utils");

const EVM_VERSION = "cancun";
const OPTIMIZER_RUNS = 200;
const SIZE_LIMIT = 24_576;

/** [file, contract, artifact basename, TS export prefix] - in deploy order. */
const DEPLOYABLE = [
  ["NutsToken.sol", "NutsToken", "nutstoken", "NUTS_TOKEN"],
  ["Nutshell.sol", "Nutshell", "nutshell", "NUTSHELL"],
  ["V4SwapAdapter.sol", "V4SwapAdapter", "v4swapadapter", "V4_SWAP_ADAPTER"],
  ["NutsPresale.sol", "NutsPresale", "nutspresale", "NUTS_PRESALE"],
];

function walk(dir, acc = []) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (e.endsWith(".sol")) acc.push(p);
  }
  return acc;
}

const sources = {};
for (const f of walk(CONTRACTS)) {
  sources[relative(CONTRACTS, f).split("\\").join("/")] = { content: readFileSync(f, "utf8") };
}

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: OPTIMIZER_RUNS },
    evmVersion: EVM_VERSION,
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};

// Relative imports only - an external dependency must never reach the verified source set.
const findImport = (path) =>
  sources[path] ? { contents: sources[path].content } : { error: `import outside contracts/: ${path}` };

console.log(`solc ${solc.version()}  evmVersion=${EVM_VERSION} optimizer.runs=${OPTIMIZER_RUNS}`);
const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImport }));

let problems = 0;
for (const e of output.errors ?? []) {
  problems++;
  console.error(`\n${e.formattedMessage}`);
}
if (problems) {
  console.error(`\n${problems} error(s)/warning(s) - nothing written.`);
  process.exit(1);
}

mkdirSync(OUT, { recursive: true });
for (const [file, name, base, prefix] of DEPLOYABLE) {
  const c = output.contracts[file][name];
  const bytecode = "0x" + c.evm.bytecode.object;
  const runtimeSize = c.evm.deployedBytecode.object.length / 2;
  const flag = runtimeSize > SIZE_LIMIT ? "  !! OVER THE 24,576-BYTE LIMIT" : "";
  console.log(`  ${name.padEnd(14)} runtime ${String(runtimeSize).padStart(6)} B${flag}`);
  if (flag) process.exitCode = 1;

  writeFileSync(
    join(OUT, `${base}-artifact.ts`),
    `// GENERATED by scripts/compile-contracts.mjs - do not edit.\n` +
      `export const ${prefix}_ABI = ${JSON.stringify(c.abi, null, 2)} as const;\n` +
      `export const ${prefix}_BYTECODE = "${bytecode}" as \`0x\${string}\`;\n` +
      `export const ${prefix}_RUNTIME_SIZE = ${runtimeSize};\n`
  );
}
writeFileSync(join(OUT, "standard-json-input.json"), JSON.stringify(input, null, 2));

// The frontend gets the hub ABI ONLY - no bytecode, nothing from server/config.ts. web/ is its
// own package and never imports from server/, so the ABI is copied rather than shared.
const hubAbi = output.contracts["Nutshell.sol"]["Nutshell"].abi;
mkdirSync(join(ROOT, "web", "src", "lib"), { recursive: true });
writeFileSync(
  join(ROOT, "web", "src", "lib", "nutshell-abi.ts"),
  `// GENERATED by scripts/compile-contracts.mjs - do not edit.\nexport const NUTSHELL_ABI = ${JSON.stringify(hubAbi, null, 2)} as const;\n`
);
console.log("wrote web/src/lib/nutshell-abi.ts");
const presaleAbi = output.contracts["NutsPresale.sol"]["NutsPresale"].abi;
writeFileSync(
  join(ROOT, "web", "src", "lib", "presale-abi.ts"),
  `// GENERATED by scripts/compile-contracts.mjs - do not edit.\nexport const PRESALE_ABI = ${JSON.stringify(presaleAbi, null, 2)} as const;\n`
);
console.log("wrote web/src/lib/presale-abi.ts");
console.log(`wrote ${DEPLOYABLE.length} artifacts to server/utils/`);
